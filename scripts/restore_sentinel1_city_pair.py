"""Restore city radar inputs into a new directory from verified ZIPs."""

import argparse
import json
from pathlib import Path
import shutil
import tempfile

import numpy as np
import rasterio

import verify_sentinel1_city_rebuild as rebuild

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs/sentinel1_city_pair/source_manifest.json"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="New output directory; existing directories are never replaced.",
    )
    args = parser.parse_args()
    output = args.output.resolve()

    if output.exists():
        raise SystemExit(f"Output already exists: {output}")

    metadata = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if metadata.get("approved_for_training") is not False:
        raise ValueError("Unexpected training approval status.")

    output.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(
        prefix=".sentinel1_restore_", dir=output.parent
    ))
    written = []

    try:
        def writer(filename, values, crs, transform):
            if (
                str(crs) != metadata["crs"]
                or list(values.shape) != metadata["shape_rows_columns"]
                or not np.allclose(
                    list(transform), metadata["transform"], rtol=0, atol=1e-8
                )
            ):
                raise ValueError("Rebuilt grid differs from the manifest.")

            target = stage / filename
            is_mask = values.dtype == np.uint8
            profile = {
                "driver": "GTiff",
                "height": values.shape[0],
                "width": values.shape[1],
                "count": 1,
                "crs": crs,
                "transform": transform,
                "dtype": str(values.dtype),
                "nodata": 255 if is_mask else np.nan,
                "compress": "deflate",
            }
            with rasterio.open(target, "w", **profile) as dst:
                dst.write(values, 1)

            with rasterio.open(target) as saved:
                if not np.array_equal(
                    saved.read(1), values, equal_nan=True
                ):
                    raise ValueError(f"Write verification failed: {filename}")
            written.append(filename)

        rebuild.main(manifest_path=MANIFEST, writer=writer)

        if len(written) != 12 or len(set(written)) != 12:
            raise ValueError("Expected twelve distinct raster outputs.")

        (stage / "provenance.json").write_text(
            json.dumps(metadata, indent=2, allow_nan=False) + "\n",
            encoding="utf-8",
        )

        if output.exists():
            raise FileExistsError("Output appeared during processing.")
        stage.rename(output)

    except BaseException:
        if stage.exists():
            shutil.rmtree(stage)
        raise

    print("\nRestored 12 rasters and provenance:", output)
    print("The comparison PNG is not generated by this command.")
    print("Original archives, existing city files and models unchanged.")


if __name__ == "__main__":
    main()
